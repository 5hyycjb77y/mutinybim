/**
 * @jest-environment node
 *
 * The add-on rulebook's API report (round 6, R-3): every name `@permitzip/bim-pack`
 * exports and every extension point it knows, with its version, generated from
 * the code and checked in as `API-REPORT.md`. A change to the rulebook shows up
 * as a diff in review and fails here until the report is regenerated
 * (`C6X_API_REPORT_WRITE=1`), so nobody changes the contract by accident.
 * A removed name or a point whose major version changed is a breaking change:
 * it needs a contract major bump in PACK-CONTRACT.md as well.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { KNOWN_POINTS, PACK_CONTRACT_VERSION } from "@permitzip/bim-pack";

const PACKAGE = path.resolve(__dirname, "..");
const REPORT = path.join(PACKAGE, "API-REPORT.md");

/**
 * Names exported by `src/index.ts`, each marked type or value, from its export
 * lists. A star re-export of one of the package's own files (`./runtime`, the
 * entry first-party add-ons import) is read through, so the report lists names.
 */
function exportedNames(file = "src/index.ts", names = new Set<string>()): string[] {
  const source = readFileSync(path.join(PACKAGE, file), "utf8");
  for (const m of source.matchAll(/export\s+\*\s+from\s+"(\.\/[^"]+)"/g)) exportedNames(path.join(path.dirname(file), `${m[1]}.ts`), names);
  for (const m of source.matchAll(/export\s+(type\s+)?\{([^}]*)\}/g)) {
    const allTypes = Boolean(m[1]);
    for (const raw of (m[2] ?? "").split(",")) {
      const part = raw.replace(/\/\/.*$/gm, "").trim();
      if (!part) continue;
      const isType = allTypes || part.startsWith("type ");
      const name = part.replace(/^type\s+/, "").split(/\s+as\s+/).pop()?.trim() ?? part;
      names.add(`${isType ? "type " : ""}${name}`);
    }
  }
  for (const m of source.matchAll(/export\s+\*\s+from\s+"([^."][^"]*)"/g)) names.add(`* from ${m[1]}`);
  return [...names].sort((a, b) => a.replace(/^type /, "").localeCompare(b.replace(/^type /, "")));
}

function report(): string {
  const points = [...KNOWN_POINTS].sort((a, b) => a.id.localeCompare(b.id)).map((p) => `| \`${p.id}\` | ${p.version} | ${p.label} |`);
  return [
    "# @permitzip/bim-pack API report",
    "",
    "Generated by `packages/bim-pack/__tests__/c6x-api-report.test.ts` (`C6X_API_REPORT_WRITE=1`). Do not edit by hand.",
    "",
    `Contract version: **${PACK_CONTRACT_VERSION}**`,
    "",
    "## Extension points",
    "",
    "| Id | Major | What it holds |",
    "| --- | --- | --- |",
    ...points,
    "",
    "## Exports",
    "",
    ...exportedNames().map((n) => `- \`${n}\``),
    "",
  ].join("\n");
}

describe("add-on rulebook API report", () => {
  it("matches the checked-in API-REPORT.md", () => {
    const now = report();
    if (process.env.C6X_API_REPORT_WRITE === "1") writeFileSync(REPORT, now);
    expect(readFileSync(REPORT, "utf8")).toBe(now);
  });
});
