/**
 * Reads the drawing-note fonts shipped in packages/bim-sheets/fonts and writes
 * their glyph advances to the kernel, so the one text layout engine measures
 * with exactly the widths the PDF embeds and the browser loads.
 *
 * Re-run only when a font file changes (the PDF writer refuses a font whose
 * hash no longer matches these metrics):
 *
 *   npx tsx packages/bim-sheets/scripts/build-note-font-metrics.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import fontkit from "@pdf-lib/fontkit";

const here = path.dirname(fileURLToPath(import.meta.url));
const FONTS_DIR = path.resolve(here, "../fonts");
const OUT = path.resolve(here, "../../bim-kernel/src/annotation/font-metrics.generated.ts");

const FACES = [
  { key: "regular", file: "LiberationSans-Regular.ttf" },
  { key: "bold", file: "LiberationSans-Bold.ttf" },
  { key: "italic", file: "LiberationSans-Italic.ttf" },
  { key: "boldItalic", file: "LiberationSans-BoldItalic.ttf" },
] as const;

/** Characters a drafting note may use: printable ASCII, Latin-1, and drafting punctuation and symbols. */
function wantedCodepoints(): number[] {
  const out: number[] = [];
  for (let c = 0x20; c <= 0x7e; c++) out.push(c);
  for (let c = 0xa0; c <= 0xff; c++) out.push(c);
  out.push(0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2032, 0x2033, 0x2212, 0x2248, 0x2260, 0x2264, 0x2265, 0x0394, 0x03a9, 0x03bc, 0x2190, 0x2191, 0x2192, 0x2193, 0x25e6, 0x2116, 0x2300);
  return out;
}

interface FaceMetrics {
  readonly sha256: string;
  readonly unitsPerEm: number;
  readonly ascent: number;
  readonly descent: number;
  readonly lineGap: number;
  readonly capHeight: number;
  readonly underlinePosition: number;
  readonly underlineThickness: number;
  readonly widths: number[];
}

function main() {
  const loaded = FACES.map((face) => {
    const bytes = readFileSync(path.join(FONTS_DIR, face.file));
    const font = fontkit.create(bytes);
    return { face, font, sha256: createHash("sha256").update(bytes).digest("hex") };
  });
  // Only characters every face really draws (glyph 0 is .notdef: an empty box in print).
  const codepoints = wantedCodepoints().filter((cp) => loaded.every(({ font }) => font.glyphForCodePoint(cp).id !== 0));
  const dropped = wantedCodepoints().filter((cp) => !codepoints.includes(cp));
  const faces: Record<string, FaceMetrics> = {};
  for (const { face, font, sha256 } of loaded) {
    faces[face.key] = {
      sha256,
      unitsPerEm: font.unitsPerEm,
      ascent: font.ascent,
      descent: font.descent,
      lineGap: font.lineGap,
      capHeight: font.capHeight,
      underlinePosition: font.underlinePosition,
      underlineThickness: font.underlineThickness,
      widths: codepoints.map((cp) => font.glyphForCodePoint(cp).advanceWidth),
    };
  }
  const body = [
    "// Generated by packages/bim-sheets/scripts/build-note-font-metrics.ts from packages/bim-sheets/fonts. Do not edit.",
    `// Characters the fonts do not draw (left out): ${dropped.map((cp) => `U+${cp.toString(16).toUpperCase().padStart(4, "0")}`).join(" ") || "none"}.`,
    "",
    "export const NOTE_FONT_FILES = " + JSON.stringify(Object.fromEntries(FACES.map((f) => [f.key, f.file]))) + " as const;",
    "",
    "/** Unicode code points every face draws, in the order of each face's `widths`. */",
    `export const NOTE_FONT_CODEPOINTS: readonly number[] = ${JSON.stringify(codepoints)};`,
    "",
    "/** Per face: font-unit metrics and the advance of each code point in NOTE_FONT_CODEPOINTS. */",
    `export const NOTE_FONT_FACES = ${JSON.stringify(faces)} as const;`,
    "",
  ].join("\n");
  writeFileSync(OUT, body);
  console.log(`[note-font-metrics] wrote ${codepoints.length} code points x ${FACES.length} faces to ${path.relative(process.cwd(), OUT)}; left out ${dropped.length}`);
}

main();
