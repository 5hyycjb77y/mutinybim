#!/usr/bin/env node
// Writes src/examples.generated.ts from examples/*.ts, so the kit carries the
// example scripts' source wherever it runs (a sealed runner, a browser, a
// hosted tool server) without reading files. examples-generated.test.ts fails
// when this file is stale: run `node packages/bim-script/scripts/write-examples.mjs`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function examplesModule() {
  const dir = path.join(root, "examples");
  const names = readdirSync(dir).filter((f) => f.endsWith(".ts")).sort();
  const entries = names.map((f) => `  ${JSON.stringify(f.replace(/\.ts$/, ""))}: ${JSON.stringify(readFileSync(path.join(dir, f), "utf8"))},`);
  return `// Generated by scripts/write-examples.mjs from examples/*.ts. Do not edit by hand.\n\n/** Each example script's source, by name (its file name without .ts). */\nexport const KIT_EXAMPLE_SOURCES: Readonly<Record<string, string>> = {\n${entries.join("\n")}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(root, "src/examples.generated.ts"), examplesModule());
  process.stdout.write("wrote packages/bim-script/src/examples.generated.ts\n");
}
