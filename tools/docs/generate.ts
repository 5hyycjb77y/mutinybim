/** Every generated file, by repository-relative path. */
export async function docFiles(): Promise<Files> {
  installFirstPartyAddOns();
  const tools = await listAllTools();
  const files: Files = new Map();
  files.set(`${REFERENCE_DIR}/README.md`, indexPage(tools));
  kitPages(files);
  files.set(`${REFERENCE_DIR}/recipes.md`, recipesPage());
  files.set(`${REFERENCE_DIR}/examples.md`, examplesPage());
  files.set(`${REFERENCE_DIR}/commands.md`, commandsPage());
  files.set(`${REFERENCE_DIR}/calcs.md`, calcsPage());
  files.set(`${REFERENCE_DIR}/reads.md`, readsPage());
  files.set(`${REFERENCE_DIR}/add-ons.md`, addOnsPage());
  files.set(`${REFERENCE_DIR}/mcp-tools.md`, toolsPage(tools));
  files.set("llms.txt", llmsTxt(tools));
  return files;
}

/** Hand-written docs llms-full.txt carries ahead of the generated reference, in reading order. */
const FULL_TEXT_DOCS = ["AGENTS.md", "docs/CONNECT-AN-AGENT.md", "docs/SCRIPTING.md"];

/**
 * Files only the docs site publishes (too large to keep in git, and rebuilt on
 * every deploy): the kit's declarations, and llms-full.txt, every page an agent
 * needs in one file.
 */
export function siteOnlyFiles(committed: Files, readRepoFile: (path: string) => string): Files {
  const generated = [...committed].filter(([path]) => path.startsWith(`${REFERENCE_DIR}/`) && path.endsWith(".md"));
  const parts = [
    ...FULL_TEXT_DOCS.map((path) => [path, readRepoFile(path)] as const),
    ...generated.map(([path, text]) => [path, text.replace(`${HEADER}\n\n`, "")] as const),
  ];
  const full = [
    committed.get("llms.txt") ?? "",
    ...parts.map(([path, text]) => `\n---\n\n<!-- ${path} -->\n\n${text.trimEnd()}\n`),
  ].join("");
  return new Map([
    [`${REFERENCE_DIR}/script-kit.d.ts`, kitDeclarations()],
    ["llms-full.txt", full],
  ]);
}
