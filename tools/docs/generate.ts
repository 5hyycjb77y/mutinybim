const HEADER = "<!-- Generated by tools/docs (npm run docs). Do not edit by hand: change the code it reads, then regenerate. -->";

/** Kit namespaces in the order a script usually meets them, with a page title and a line on what each is for. */
const KIT_PAGES: readonly { readonly ns: string; readonly file: string; readonly title: string; readonly about: string }[] = [
  { ns: "ctx", file: "ctx", title: "ctx: the script context", about: "What a script's `run(ctx)` gets: reading the model slice it declared, sending edits, running calcs and reads, proposals, labels and reports." },
  { ns: "units", file: "units", title: "units", about: "Typed lengths and other measures. Every length a kit function takes is a `units.*` value, never a bare number." },
  { ns: "building", file: "building", title: "building", about: "Levels, grids, walls, doors, windows, floors, ceilings, roofs, stairs, rooms and spaces." },
  { ns: "routes", file: "routes", title: "routes", about: "Duct, pipe and conduit runs: sizes, systems, slopes, where a run starts and ends, and connecting into a run." },
  { ns: "equipment", file: "equipment", title: "equipment", about: "Placing parts (equipment, fixtures, devices) by type, and their connectors." },
  { ns: "parts", file: "parts", title: "parts", about: "Making part types: a part's bodies, connectors and parameters." },
  { ns: "PartBuilder", file: "part-builder", title: "PartBuilder", about: "The builder `parts.part()` returns: boxes, extrusions, sweeps, connectors and parameters on one part type." },
  { ns: "documents", file: "documents", title: "documents", about: "Views, sheets, schedules, tags, notes, dimensions and the rest of a drawing set." },
  { ns: "checks", file: "checks", title: "checks", about: "Checks a script runs on its own output before a person sees it." },
  { ns: "", file: "define-script", title: "defineScript", about: "The one top-level function: a script's kind, what it reads, its parameters and its `run`." },
];

type Files = Map<string, string>;

/** Escape a value for one Markdown table cell. */
function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();
}

function firstSentence(text: string): string {
  const flat = text.replace(/\s*\n\s*/g, " ").trim();
  // A sentence ends at . ! or ? followed by a capital (or the end), so "e.g. `grid`" stays whole.
  const m = flat.match(/^(.+?[.!?])(?=\s+[A-Z]|$)/);
  return m?.[1] ?? flat;
}

function page(title: string, intro: string, body: readonly string[]): string {
  return [HEADER, "", `# ${title}`, "", intro, "", ...body].join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

function nsOf(e: KitEntry): string {
  const dot = e.name.indexOf(".");
  return dot < 0 ? "" : e.name.slice(0, dot);
}


function kitPages(files: Files): void {
  for (const p of KIT_PAGES) {
    const entries = KIT_ENTRIES.filter((e) => nsOf(e) === p.ns);
    if (entries.length === 0) continue;
    const toc = entries.map((e) => `- [\`${e.name}\`](#${slug(e.name)}): ${firstSentence(e.summary)}`);
    const body = entries.flatMap((e) => [
      `## ${e.name}`,
      "",
      e.summary,
      "",
      "```ts",
      e.signature,
      "```",
      "",
      ...(e.topics.length ? [`Topics: ${e.topics.join(", ")}`, ""] : []),
      "<details><summary>Example script</summary>",
      "",
      "```ts",
      e.example.trimEnd(),
      "```",
      "",
      "</details>",
      "",
    ]);
    files.set(`${REFERENCE_DIR}/script-kit/${p.file}.md`, page(p.title, `${p.about}\n\nEvery example below is a complete script that passes the kit's checks; the kit's tests run each one.`, [...toc, "", ...body]));
  }
  const known = new Set(KIT_PAGES.map((p) => p.ns));
  const stray = [...new Set(KIT_ENTRIES.map(nsOf))].filter((ns) => !known.has(ns));
  if (stray.length) throw new Error(`tools/docs: kit namespace(s) ${stray.join(", ")} have no page in KIT_PAGES; add one.`);
}

function recipesPage(): string {
  const body = KIT_RECIPES.flatMap((r) => [
    `## ${r.name}`,
    "",
    `Task: ${r.task}`,
    "",
    r.summary,
    "",
    ...r.steps.map((s, i) => `${i + 1}. ${s}`),
    "",
    `Uses: ${r.uses.map((u) => `\`${u}\``).join(", ")}`,
    "",
  ]);
  return page("Script recipes", "Worked tasks: which kit functions to call, in which order. Start from the closest one.", body);
}

function examplesPage(): string {
  const body = KIT_EXAMPLES.flatMap((x) => [
    `## ${x.title}`,
    "",
    x.builds,
    "",
    `Run it: \`npm run example -- ${x.name}\`, or paste it to an assistant connected to the tool server. Source: [\`${KIT_EXAMPLES_PATH}/${x.name}.ts\`](../../${KIT_EXAMPLES_PATH}/${x.name}.ts).`,
    "",
    "```ts",
    x.source.trimEnd(),
    "```",
    "",
  ]);
  return page("Example scripts", "Whole scripts that each build something complete. Copy the closest one and change it.", body);
}

function commandsPage(): string {
  const commands = scriptCommands();
  const toc = [`| Command | From |`, `| --- | --- |`, ...commands.map((c) => `| [\`${c.type}\`](#${slug(c.type)}) | ${c.from} |`)];
  const body = commands.flatMap((c) => {
    const f = commandFields(c.type);
    return [`## ${c.type}`, "", ...(f?.fields ?? []).map((l) => `- ${l}`), ""];
  });
  return page(
    "Edit commands (ctx.edit)",
    `Every single edit a script may send with \`ctx.edit\`, read from the kernel's own schemas and those of the add-ons in force: ${commands.length} commands. The kit functions build these for you; reach for a command directly only when no kit function fits.`,
    [...toc, "", ...body],
  );
}

function calcsPage(): string {
  const calcs = [...builtinCalcRegistry().list()].sort((a, b) => a.id.localeCompare(b.id));
  const rows = calcs.map((c) => `| \`${c.id}\` | ${cell(c.title)} | ${c.domain} | ${cell(c.summary)} |`);
  return page(
    "Calcs (ctx.calc)",
    `The calculations a script runs with \`ctx.calc({ calc: "<id>", inputs })\`: ${calcs.length} calcs. Each returns its values with their units. \`ctx.calcs()\` lists them from inside a script.`,
    ["| Calc | Title | Domain | What it does |", "| --- | --- | --- | --- |", ...rows],
  );
}

function readsPage(): string {
  const reads = [...activePackSet().items(PACK_READ_POINT)].sort((a, b) => a.id.localeCompare(b.id));
  const rows = reads.map((r) => `| \`${r.id}\` | ${cell(r.label)} |`);
  return page("Pack reads (ctx.read)", `What the add-ons let a script read with \`ctx.read("<id>", input)\`: ${reads.length} reads. A read never edits.`, ["| Read | What it returns |", "| --- | --- |", ...rows]);
}

function addOnSection(p: Pack): string[] {
  const m = p.manifest;
  const points = new Map<string, number>();
  for (const c of p.contributions) points.set(c.pointLabel, (points.get(c.pointLabel) ?? 0) + c.items.length);
  const rows = [...points].filter(([, n]) => n > 0).sort((a, b) => a[0].localeCompare(b[0]));
  return [
    `## ${m.name}`,
    "",
    `Id \`${m.id}\`, version ${m.version}, written for kernel contract ${m.kernel}.${m.requires?.length ? ` Builds on: ${m.requires.map((r) => `\`${r.id}\` ${r.range}`).join(", ")}.` : ""}`,
    "",
    ...(m.description ? [m.description, ""] : []),
    "| What it contributes | Items |",
    "| --- | --- |",
    ...rows.map(([label, n]) => `| ${cell(label)} | ${n} |`),
    "",
  ];
}

function addOnsPage(): string {
  return page(
    "Add-ons",
    "Every trade is an add-on that plugs into the kernel's versioned extension points ([the add-on contract](../ADD-ON-CONTRACT.md)). These are the add-ons in this repository and what each one contributes, counted from the add-on itself.",
    [
      "## First-party bundle",
      "",
      "Installed together by `@permitzip/bim-first-party`.",
      "",
      ...FIRST_PARTY_ADDONS.flatMap((p) => addOnSection(p).map((l) => l.replace(/^## /, "### "))),
      "## Other add-ons",
      "",
      ...[CIVIL_PACK, SITE_PACK, DEVELOPMENT_PACK].flatMap((p) => addOnSection(p).map((l) => l.replace(/^## /, "### "))),
    ],
  );
}

interface ListedTool {
  readonly name: string;
  readonly description?: string;
  readonly inputSchema: { readonly properties?: Record<string, unknown>; readonly required?: readonly string[] };
}

/** The tool server's full list (every family on), from an in-memory server over the MCP SDK, as an assistant sees it. */
async function listAllTools(): Promise<readonly ListedTool[]> {
  const models = startInMemoryModelServer();
  const dir = mkdtempSync(join(tmpdir(), "mutinybim-docs-"));
  try {
    await models.seed(starterModel("demo"));
    const host = createLocalHost({ server: models, repoRoot: REPO_ROOT, approve: "auto" });
    const server = createBimToolServer({ host, schemas: LOCAL_SCHEMAS, packs: [localToolPacks(host, dir)], families: "all" });
    const client = new Client({ name: "mutinybim-docs", version: "1.0.0" });
    const [a, b] = InMemoryTransport.createLinkedPair();
    await Promise.all([server.connect(b), client.connect(a)]);
    const { tools } = await client.listTools();
    await client.close();
    return tools as readonly ListedTool[];
  } finally {
    await models.close();
    rmSync(dir, { recursive: true, force: true });
  }
}

function toolsPage(tools: readonly ListedTool[]): string {
  const byName = new Map(tools.map((t) => [t.name, t]));
  const listed = new Set<string>();
  const body: string[] = [];
  for (const pack of BIM_TOOL_PACKS) {
    const members = pack.tools.map((n) => byName.get(n)).filter((t): t is ListedTool => Boolean(t));
    if (members.length === 0) continue;
    const address = pack.slug === "core" ? "`/mcp` (the default list)" : `\`/packs/${pack.slug}/mcp\`, \`--packs ${pack.slug}\`, or \`bim_enable_pack\` in a session`;
    body.push(`## ${pack.label}`, "", `Family \`${pack.slug}\`: ${pack.purpose}.`, "", `Turn it on: ${address}.`, "");
    for (const t of members) {
      listed.add(t.name);
      const props = Object.keys(t.inputSchema.properties ?? {});
      const required = new Set(t.inputSchema.required ?? []);
      body.push(`### ${t.name}`, "", (t.description ?? "").trim(), "");
      if (props.length) body.push(`Input: ${props.map((p) => `\`${p}\`${required.has(p) ? "" : "?"}`).join(", ")}`, "");
    }
  }
  const rest = tools.filter((t) => !listed.has(t.name));
  if (rest.length) {
    body.push("## Other tools", "");
    for (const t of rest) body.push(`### ${t.name}`, "", `Family: ${toolFamily(t.name) ?? "none"}.`, "", (t.description ?? "").trim(), "");
  }
  return page(
    "Tool server (MCP) tools",
    `What an assistant connected to the tool server can call: ${tools.length} tools. The default list is the core pack, at most ${CORE_TOOL_BUDGET} tools; every other family is opt-in. The script API is the product: an assistant works by writing a script ([the kit](script-kit/ctx.md)), not by calling many tools. \`?\` marks an optional input.`,
    body,
  );
}

function indexPage(tools: readonly ListedTool[]): string {
  const kitLinks = KIT_PAGES.filter((p) => KIT_ENTRIES.some((e) => nsOf(e) === p.ns)).map((p) => `  - [${p.title}](script-kit/${p.file}.md): ${KIT_ENTRIES.filter((e) => nsOf(e) === p.ns).length} functions`);
  return page(
    "MutinyBIM reference",
    "Generated from the code on every change, for people and for agents. For guides and the why behind the design, start at the [docs index](../README.md).",
    [
      "## Writing scripts",
      "",
      `- [Example scripts](examples.md): ${KIT_EXAMPLES.length} whole scripts to copy`,
      `- [Recipes](recipes.md): ${KIT_RECIPES.length} worked tasks`,
      `- Script kit: ${KIT_ENTRIES.length} functions`,
      ...kitLinks,
      `- [Edit commands](commands.md): ${scriptCommands().length} commands \`ctx.edit\` takes`,
      `- [Calcs](calcs.md): ${builtinCalcRegistry().list().length} calculations \`ctx.calc\` runs`,
      `- [Pack reads](reads.md): ${activePackSet().items(PACK_READ_POINT).length} reads \`ctx.read\` runs`,
      "- TypeScript declarations: the whole kit as one `script-kit.d.ts`, for an agent or editor that type-checks scripts. The docs site builds it; `kitDeclarations()` in `@permitzip/bim-script` returns it.",
      "",
      "## The platform",
      "",
      `- [Add-ons](add-ons.md): ${FIRST_PARTY_ADDONS.length + 3} add-ons and what each contributes`,
      `- [Tool server tools](mcp-tools.md): ${tools.length} MCP tools in ${BIM_TOOL_PACKS.length} families`,
    ],
  );
}

