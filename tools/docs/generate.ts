/**
 * The generated reference under docs/reference/ and the agent index llms.txt,
 * built from the code itself: the script kit's entries, recipes and examples,
 * the kernel's edit commands, the calcs and pack reads, the add-ons in this
 * repository and the tool server's tool list. Nothing here is written by hand,
 * so a renamed function, a new calc or a new tool changes the docs in the same
 * commit (`npm run docs`), and `docs-current.test.ts` fails when they drift.
 *
 * Output is deterministic: no dates, no absolute paths, stable order.
 */
